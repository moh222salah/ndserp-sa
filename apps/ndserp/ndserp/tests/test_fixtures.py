"""Guard rails for the fixture list.

These tests exist because the app previously shipped fixtures that overwrote
records belonging to Frappe and ERPNext. They fail loudly if that regresses.
"""

import frappe
from frappe.tests.utils import FrappeTestCase

from ndserp import hooks

# Doctypes that must never be exported without filters - an unfiltered export
# pulls in the records of every other installed app.
MUST_BE_FILTERED = {
	"Client Script",
	"Server Script",
	"Print Format",
	"Report",
	"Custom Field",
	"Custom DocPerm",
	"Property Setter",
	"Workspace",
	"Role",
	"Role Profile",
}


class TestFixtures(FrappeTestCase):
	def test_every_fixture_has_filters(self):
		for fixture in hooks.fixtures:
			doctype = fixture.get("dt") or fixture.get("doctype")
			with self.subTest(doctype=doctype):
				self.assertIn(
					doctype,
					MUST_BE_FILTERED,
					f"{doctype} is not in the reviewed list - add it deliberately",
				)
				self.assertTrue(
					fixture.get("filters"),
					f"fixture for {doctype} has no filters and would export other apps' records",
				)

	def test_no_foreign_print_formats_are_shipped(self):
		"""Print formats must belong to the Ndserp module.

		Shipping a standard ERPNext print format (module = Accounts, Regional)
		overwrites ERPNext's own copy on every migrate.
		"""
		for record in _load_fixture_file("print_format"):
			self.assertEqual(
				record.get("module"), "Ndserp", f"{record.get('name')} is not an Ndserp print format"
			)

	def test_only_whitelisted_custom_fields_are_shipped(self):
		"""Custom fields are matched by name, never by doctype.

		pos_next adds `posa_*` fields to Sales Invoice and Frappe adds
		`ta_amend_archived`; a doctype-wide filter would ship all of them.
		"""
		for record in _load_fixture_file("custom_field"):
			with self.subTest(field=record.get("name")):
				self.assertIn(
					record.get("name"),
					hooks.NDSERP_CUSTOM_FIELDS,
					f"{record.get('name')} is not owned by ndserp",
				)
				self.assertFalse(
					record.get("is_system_generated"),
					f"{record.get('name')} is generated by framework code and must not be shipped",
				)

	def test_only_whitelisted_roles_are_shipped(self):
		"""Roles are matched by name so standard Frappe/ERPNext roles stay out."""
		for record in _load_fixture_file("role"):
			with self.subTest(role=record.get("name")):
				self.assertIn(
					record.get("name"),
					hooks.NDSERP_ROLES,
					f"{record.get('name')} is not in NDSERP_ROLES",
				)

	def test_only_whitelisted_role_profiles_are_shipped(self):
		for record in _load_fixture_file("role_profile"):
			with self.subTest(profile=record.get("name")):
				self.assertIn(
					record.get("name"),
					hooks.NDSERP_ROLE_PROFILES,
					f"{record.get('name')} is not in NDSERP_ROLE_PROFILES",
				)

	def test_custom_docperm_only_for_whitelisted_roles(self):
		for record in _load_fixture_file("custom_docperm"):
			with self.subTest(name=record.get("name")):
				self.assertIn(
					record.get("role"),
					hooks.NDSERP_CUSTOM_DOCPERM_ROLES,
					f"{record.get('name')} role is not whitelisted",
				)

	def test_module_nds_profiles_never_include_system_manager(self):
		forbidden = {"System Manager", "Administrator", "Workspace Manager"}
		for record in _load_fixture_file("role_profile"):
			name = record.get("name") or ""
			if not name.endswith(" NDS"):
				continue
			roles = {row.get("role") for row in record.get("roles") or []}
			with self.subTest(profile=name):
				self.assertFalse(
					roles & forbidden,
					f"{name} must not include {roles & forbidden}",
				)

	def test_workspaces_have_a_single_source(self):
		"""Workspaces live in fixtures only.

		A module workspace folder (ndserp/ndserp/workspace/) would be a second,
		silently diverging source that migrate also imports.
		"""
		import os

		folder = frappe.get_app_path("ndserp", "ndserp", "workspace")
		self.assertFalse(os.path.isdir(folder), "workspaces are duplicated in a module folder")


def _load_fixture_file(name: str) -> list[dict]:
	import json
	import os

	path = frappe.get_app_path("ndserp", "fixtures", f"{name}.json")

	if not os.path.exists(path):
		return []

	with open(path) as handle:
		return json.load(handle)
